"""
bundling/licenses_bundle.py -- write licenses-bundle.txt (the file NOTICE promises).

For every package pinned in requirements-lock.txt it records the name, the
version, the licence declared in the package metadata, and the full text of any
licence file the package ships. Packages with no licence text are listed under
their own heading, never skipped.

Standard library only, and meant to be run with the BUILD VENV's python
(bundling/build.py step 4b does that), because that is where the lock is
installed -- not in the interpreter that runs build.py.

    <build venv python> bundling/licenses_bundle.py --lock requirements-lock.txt --out licenses-bundle.txt

Exit codes: 0 written; 2 the file could not be produced (for example a locked
package is not installed). A failure here fails the build.
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from importlib import metadata
from pathlib import Path
from typing import Iterable, Sequence

_LICENCE_FILE = re.compile(r"(^|/)(licen[cs]e|copying|notice|authors)[^/]*$", re.IGNORECASE)
_LOCK_LINE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s\\;]+)")
_RULE = "=" * 78


@dataclass
class PackageRecord:
    name: str
    version: str
    licence: str = ""
    texts: list = field(default_factory=list)  # [(file name, text)]


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def locked_names(lock_text: str) -> list:
    """Package names pinned in a pip lock file, in file order."""
    names = []
    for line in lock_text.splitlines():
        m = _LOCK_LINE.match(line)
        if m:
            names.append(m.group(1))
    return names


def declared_licence(dist) -> str:
    """The licence the package declares: License-Expression, License, or a
    'License ::' classifier. Long License fields (a pasted text) are cut."""
    md = dist.metadata
    parts = []
    expr = md.get("License-Expression")
    if expr:
        parts.append(expr.strip())
    lic = (md.get("License") or "").strip()
    if lic and lic.upper() != "UNKNOWN":
        parts.append(lic if len(lic) <= 200 else lic[:200].rstrip() + " ...")
    for c in md.get_all("Classifier") or []:
        if c.startswith("License ::"):
            parts.append(c.split("::", 1)[1].strip().lstrip(": ").strip())
    seen, out = set(), []
    for p in parts:
        if p and p not in seen:
            seen.add(p)
            out.append(p)
    return "; ".join(out)


def licence_texts(dist) -> list:
    out = []
    for f in dist.files or []:
        posix = f.as_posix()
        if ".dist-info/" not in posix and ".egg-info/" not in posix:
            continue
        if not _LICENCE_FILE.search(posix):
            continue
        try:
            text = dist.locate_file(f).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if text.strip():
            out.append((posix.rsplit("/", 1)[-1], text.strip("\n")))
    return sorted(out)


def collect(names: Iterable[str], dists: Iterable) -> tuple:
    """(records, missing). `dists` are importlib.metadata Distribution objects;
    `missing` lists locked names with no installed distribution."""
    by_name = {}
    for d in dists:
        n = d.metadata.get("Name")
        if n:
            by_name.setdefault(normalise(n), d)
    records, missing = [], []
    for name in names:
        d = by_name.get(normalise(name))
        if d is None:
            missing.append(name)
            continue
        records.append(PackageRecord(
            name=d.metadata["Name"], version=d.version,
            licence=declared_licence(d), texts=licence_texts(d)))
    records.sort(key=lambda r: normalise(r.name))
    return records, missing


def render(records: Sequence[PackageRecord]) -> str:
    with_text = [r for r in records if r.texts]
    without = [r for r in records if not r.texts]
    out = [
        "PA Skills Portable - third-party Python package licences",
        "",
        "Generated by the build from the installed package metadata.",
        f"Packages: {len(records)}  with licence text: {len(with_text)}  "
        f"without licence text: {len(without)}",
        "",
        "Contents",
        "  1. Packages that ship licence text",
        "  2. Packages with NO licence text in their metadata",
        "",
        _RULE, "1. Packages that ship licence text", _RULE, "",
    ]
    for r in with_text:
        out += ["-" * 78, f"{r.name} {r.version}",
                f"Declared licence: {r.licence or '(none declared)'}", "-" * 78]
        for fname, text in r.texts:
            out += [f"[{fname}]", text, ""]
        out.append("")
    out += [_RULE, "2. Packages with NO licence text in their metadata", _RULE, ""]
    if without:
        out.append("These packages ship no licence file. The licence they declare is "
                   "shown; consult the package's own project for the full text.")
        out.append("")
        for r in without:
            out.append(f"  {r.name} {r.version} - declared licence: "
                       f"{r.licence or '(none declared)'}")
    else:
        out.append("(none)")
    out.append("")
    return "\n".join(out)


def build_bundle(lock_text: str, dists: Iterable) -> tuple:
    """(text, records). Raises LookupError when a locked package is not installed."""
    records, missing = collect(locked_names(lock_text), dists)
    if missing:
        raise LookupError("locked packages not installed in this environment: "
                          + ", ".join(sorted(missing)))
    if not records:
        raise LookupError("the lock file names no packages")
    return render(records), records


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--lock", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--allow-missing", action="append", default=[], metavar="NAME",
                    help="locked package that may be absent (platform-only packages)")
    args = ap.parse_args(argv)
    try:
        lock_text = args.lock.read_text(encoding="utf-8")
        names = [n for n in locked_names(lock_text)
                 if normalise(n) not in {normalise(a) for a in args.allow_missing}]
        records, missing = collect(names, metadata.distributions())
        if missing:
            raise LookupError("locked packages not installed in this environment: "
                              + ", ".join(sorted(missing)))
        if not records:
            raise LookupError("the lock file names no packages")
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(render(records), encoding="utf-8", newline="\n")
    except Exception as exc:  # noqa: BLE001 - any failure must fail the build
        print(f"licenses_bundle: FAILED: {exc}", file=sys.stderr)
        return 2
    without = sum(1 for r in records if not r.texts)
    print(f"licenses_bundle: {len(records)} packages, {len(records) - without} with "
          f"licence text, {without} without -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
