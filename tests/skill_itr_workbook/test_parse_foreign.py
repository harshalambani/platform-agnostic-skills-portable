def test_parse_numeric_cell_real_number():
    assert pf.parse_numeric_cell(1234.5) == (1234.5, None)
    assert pf.parse_numeric_cell("1,234.50") == (1234.5, None)
    assert pf.parse_numeric_cell(0) == (0.0, None)


@pytest.mark.parametrize("glyph", ["-", "#", "*"])
def test_parse_numeric_cell_placeholder_glyphs_never_become_zero(glyph):
    value, flag = pf.parse_numeric_cell(glyph)
    assert value is None
    assert flag == f"placeholder:{glyph}"


def test_parse_numeric_cell_prose_is_flagged_not_coerced():
    value, flag = pf.parse_numeric_cell(
        "To be filled by user basis Individual slab rates"
    )
    assert value is None
    assert flag.startswith("prose:")


def test_parse_numeric_cell_empty():
    assert pf.parse_numeric_cell(None) == (None, "empty")
    assert pf.parse_numeric_cell("   ") == (None, "empty")


