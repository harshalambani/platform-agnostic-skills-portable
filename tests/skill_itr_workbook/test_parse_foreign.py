def test_missing_required_sheet_raises(tmp_path):
    from openpyxl import Workbook

    wb = Workbook()
    wb.active.title = "Not A Real Sheet"
    bogus = tmp_path / "bogus.xlsx"
    wb.save(bogus)
    with pytest.raises(pf.ForeignReportError):
        pf.load_foreign_income_report(bogus)


def test_missing_header_in_present_sheet_does_not_raise(tmp_path):
    # A present-but-empty required sheet must not raise -- only degrade
    # that one schedule to parsed=False with a warning, so other sheets in
    # the same report still get read.
    from openpyxl import Workbook

    wb = Workbook()
    wb.active.title = pf.REQUIRED_SHEETS[0]
    for name in pf.REQUIRED_SHEETS[1:]:
        wb.create_sheet(name)
    empty = tmp_path / "empty_sheets.xlsx"
    wb.save(empty)
    rep = pf.load_foreign_income_report(empty)
    assert rep.schedule_fa.parsed is False
    assert rep.schedule_fsi.parsed is False
    assert len(rep.warnings) > 0


