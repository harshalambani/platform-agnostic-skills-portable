# ---------------------------------------------------------------------------
# Deliberate non-tie: Schedule FA is a CALENDAR year, Dividend/Interest are
# a FINANCIAL year -- these are NOT expected to match, and "fixing" this
# would be wrong.
# ---------------------------------------------------------------------------

def test_schedule_fa_gross_amounts_do_not_tie_to_fy_dividend_interest(report):
    fa_gross_total = sum(
        l.gross_amount_credited for l in report.schedule_fa.equity_lots
        if l.gross_amount_credited is not None
    )
    fy_total = report.dividend.total + report.interest.total
    assert fa_gross_total != fy_total, (
        "Schedule FA reports a CALENDAR year and Dividend/Interest report a "
        "FINANCIAL year -- these figures are allowed, and expected, to "
        "differ. If this ever starts passing as equal, the fixture (or the "
        "parser) changed in a way that needs re-checking, not 'fixing' this "
        "assertion away."
    )


